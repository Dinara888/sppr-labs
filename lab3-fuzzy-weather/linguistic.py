def _by_thresholds(value, thresholds, top):
    for limit, term in thresholds:
        if value < limit:
            return term
    return top


def numeric_to_linguistic(value: float, var_name: str, city_name: str, season: str) -> str:
    """Преобразование числового значения в лингвистический терм."""
    if var_name == "temperature":
        return _by_thresholds(value, TEMP_THRESHOLDS[(city_name, season)],
                              TEMP_THRESHOLDS[f"{city_name}-{season}-top"])
    if var_name == "humidity":
        # Для Санкт-Петербурга высокая влажность - норма, порог смещён выше
        high = 90 if city_name == "Saint Petersburg" else 85
        return _by_thresholds(value, [(30, "сухо"), (45, "умеренно сухо"), (70, "нормально"),
                                      (high, "влажно")], "очень влажно")
    if var_name == "wind":
        return _by_thresholds(value, [(2, "штиль"), (5, "слабый"), (10, "умеренный"),
                                      (15, "сильный"), (20, "очень сильный")], "штормовой")
    raise ValueError(f"Неизвестная переменная: {var_name}")
