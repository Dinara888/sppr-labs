% Дату дата(Г,М,Д) переводим в число ГГГГММДД - так её удобно сравнивать.
дата_число(дата(Г, М, Д), N) :- N is Г*10000 + М*100 + Д.

% в_периоде(Дата, Начало, Конец) - дата лежит в отрезке [Начало; Конец].
в_периоде(Д, Нач, Кон) :-
    дата_число(Д, N), дата_число(Нач, N1), дата_число(Кон, N2),
    N >= N1, N =< N2.

% число_нарушений(Номер, Кол) - сколько нарушений у автомобиля.
число_нарушений(Номер, Кол) :-
    автомобиль(Номер, _, _),
    aggregate_all(count, нарушение(_, Номер, _, _, _), Кол).

% сумма_штрафов(Номер, Сумма) - общая сумма штрафов автомобиля.
сумма_штрафов(Номер, Сумма) :-
    автомобиль(Номер, _, _),
    aggregate_all(sum(Ш), ( нарушение(_, Номер, Код, _, _),
                            тип_нарушения(Код, _, Ш, _) ), Сумма).

% неоплачено(Номер, Сумма) - сумма неоплаченных штрафов.
неоплачено(Номер, Сумма) :-
    автомобиль(Номер, _, _),
    aggregate_all(sum(Ш), ( нарушение(_, Номер, Код, _, нет),
                            тип_нарушения(Код, _, Ш, _) ), Сумма).

% формат_даты(+дата(Г,М,Д), -Атом) - дата в виде ДД.ММ.ГГГГ.
формат_даты(дата(Г, М, Д), A) :- format(atom(A), '~|~`0t~d~2+.~|~`0t~d~2+.~d', [Д, М, Г]).

% ---------------------------------------------------------------------
% ПРОЕКТ 13. Статистика по всем автомобилям:
% общее количество нарушений и среднее количество на автомобиль.
% ---------------------------------------------------------------------
статистика :-
    writeln('=== Статистика нарушений по автомобилям ==='),
    format('~w~t~12|~w~t~30|~w~t~48|~w~t~58|~w~n',
           ['Номер', 'Марка', 'Владелец', 'Нарушений', 'Штрафы, руб']),
    forall(автомобиль(Н, Марка, Влад),
           ( число_нарушений(Н, К), сумма_штрафов(Н, С),
             format('~w~t~12|~w~t~30|~w~t~48|~w~t~58|~w~n', [Н, Марка, Влад, К, С]) )),
    aggregate_all(count, автомобиль(_, _, _), Авто),
    aggregate_all(count, нарушение(_, _, _, _, _), Всего),
    Среднее is Всего / Авто,
    format('Всего автомобилей: ~w~n', [Авто]),
    format('Всего нарушений: ~w~n', [Всего]),
    format('Среднее число нарушений на автомобиль: ~2f~n', [Среднее]).

% среднее_нарушений(-Среднее) - то же значение в виде переменной.
среднее_нарушений(Ср) :-
    aggregate_all(count, автомобиль(_, _, _), А),
    aggregate_all(count, нарушение(_, _, _, _, _), В),
    Ср is В / А.

% ---------------------------------------------------------------------
% ПРОЕКТ 19. Отчёт о всех нарушениях за период [Начало; Конец].
% Нарушения сортируются по дате, в конце - итоги по периоду.
% ---------------------------------------------------------------------
отчёт(Нач, Кон) :-
    формат_даты(Нач, A1), формат_даты(Кон, A2),
    format('=== Отчёт о нарушениях за период ~w - ~w ===~n', [A1, A2]),
    findall(N-нар(Ид, Ном, Код, Д, Опл),
            ( нарушение(Ид, Ном, Код, Д, Опл), в_периоде(Д, Нач, Кон),
              дата_число(Д, N) ),
            Пары),
    keysort(Пары, Отсорт),
    (   Отсорт == []
    ->  writeln('За указанный период нарушений не найдено.')
    ;   forall(member(_-нар(Ид, Ном, Код, Д, Опл), Отсорт),
               ( тип_нарушения(Код, Назв, Ш, _), автомобиль(Ном, _, Влад),
                 формат_даты(Д, ДА),
                 format('~w. ~w  ~w (~w): ~w, штраф ~w руб., оплачен: ~w~n',
                        [Ид, ДА, Ном, Влад, Назв, Ш, Опл]) )),
        length(Отсорт, Кол),
        aggregate_all(sum(Ш), ( member(_-нар(_, _, Код, _, _), Отсорт),
                                тип_нарушения(Код, _, Ш, _) ), Сум),
        aggregate_all(sum(Ш), ( member(_-нар(_, _, Код, _, нет), Отсорт),
                                тип_нарушения(Код, _, Ш, _) ), Неопл),
        format('Итого нарушений: ~w; сумма штрафов: ~w руб.; не оплачено: ~w руб.~n',
               [Кол, Сум, Неопл])
    ).

% нарушения_за_период(+Нач, +Кон, -Список) - список Ид нарушений за период.
нарушения_за_период(Нач, Кон, L) :-
    findall(Ид, ( нарушение(Ид, _, _, Д, _), в_периоде(Д, Нач, Кон) ), L).

